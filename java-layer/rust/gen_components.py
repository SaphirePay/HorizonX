"""Writes src/components_gen.rs: for every SDK type that is a JSON value in a newtype (`pub struct X(pub Value);`:
data components, dialog parts, registry data...), a downcast that gives its JSON. The Java layer uses it where Paper
hands over such an object as a value (`setData(type, CustomModelData)`, dialog bodies...).

    python gen_components.py
"""
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SDK = pathlib.Path(r'D:\Horizon\paper-engine\sdk\horizon-bukkit\src')
OUT = HERE / 'src' / 'components_gen.rs'

lib = (SDK / 'lib.rs').read_text(encoding='utf-8')
public_mods = set(re.findall(r'^pub mod (\w+);', lib, re.M))
rows = []
for f in sorted(SDK.glob('*.rs')):
    module = f.stem
    if module not in public_mods:
        continue
    text = f.read_text(encoding='utf-8')
    for name in re.findall(r'^pub struct (\w+)\(pub Value\);', text, re.M):
        rows.append((module, name, 'x.0.clone()'))
    for name in re.findall(r'^pub struct (\w+)\(pub Map<String, Value>\);', text, re.M):
        rows.append((module, name, 'serde_json::Value::Object(x.0.clone())'))
lines = ['// Generated by gen_components.py: SDK types that are a JSON value in a newtype.', '#![allow(unused)]', 'use jrt::V;', '',
         '/// The JSON of an SDK value object held by the Java layer (a data component, a dialog part...), if it is one.',
         'pub fn json_of(v: &V) -> Option<serde_json::Value> {']
for module, name, how in rows:
    lines.append(f'    if let Some(x) = jbridge::held::<horizon_bukkit::{module}::{name}>(v) {{ return Some({how}); }}')
lines += ['    None', '}', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print(f'{OUT}: {len(rows)} types')
